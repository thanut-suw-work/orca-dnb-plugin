export function cellsOf(id: PieceId, rot: Rot): Point[] {
  return SHAPES[id][rot]!;
}

export function spawnX(id: PieceId): number {
  return id === "O" ? 4 : 3;
}

export function kicksFor(id: PieceId, from: Rot, to: Rot): Kick[] {
  if (id === "O") return [[0, 0]];
  if (((from + 2) % 4) as Rot === to) return KICKS_180;
  const key = `${from}>${to}`;
  const table = id === "I" ? KICKS_I : KICKS_JLSTZ;
  return table[key] ?? [[0, 0]];
}

export function wrapRot(n: number): Rot {
  return (((n % 4) + 4) % 4) as Rot;
}
